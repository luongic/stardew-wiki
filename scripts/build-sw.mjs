// Builds the offline cache manifest for sw.js and version.json.
//
// The version is a hash of every file the site serves, so it changes whenever
// anything changes: browsers then fetch the new version as a whole (never a
// mix of old and new files). Run by the git pre-commit hook (.githooks).
//
//   node scripts/build-sw.mjs                      update if files changed (minor update)
//   node scripts/build-sw.mjs --important "Ghi chú 1" "Ghi chú 2"
//                                                  mark this version as important: visitors
//                                                  get a popup with these notes
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';

const ROOT = new URL('..', import.meta.url).pathname;
const read = f => readFileSync(ROOT + f);

// Everything the site serves: files in git (incl. staged ones, so run after
// `git add`; the pre-commit hook does), minus tooling and docs. Untracked
// files are left out: GitHub Pages wouldn't have them and the install would fail.
const files = execSync('git ls-files --cached', { cwd: ROOT, encoding: 'utf8' })
  .split('\n').filter(Boolean)
  .filter(f => existsSync(ROOT + f))
  .filter(f => !/^(scripts|\.githooks|\.github|node_modules)\//.test(f))
  .filter(f => !/(^|\/)\.|\.md$|^(package(-lock)?\.json|firestore\.rules|firebase\.json|LICENSE|sw\.js|version\.json)$/.test(f))
  .sort();

// Small files every page needs are downloaded up front; icons, portraits and
// maps are cached the first time they are shown
const precache = files.filter(f => f === 'index.html' || /^(css|js|data)\//.test(f) || /^assets\/[^/]+\.(svg|png|jpg|ico)$/.test(f));

const hash = createHash('sha256');
for (const f of files) hash.update(f).update('\0').update(read(f)).update('\0');
const content = hash.digest('hex').slice(0, 10);

const args = process.argv.slice(2);
const important = args.includes('--important');
const notes = args.filter(a => !a.startsWith('--'));

// Same files as last time: keep version.json as it is (also keeps the notes
// of an important release when the pre-commit hook runs right after it)
const current = existsSync(ROOT + 'version.json') ? JSON.parse(read('version.json')) : {};
if (current.content === content && !important) process.exit(0);

// An important release gets its own version even without file changes, so
// browsers notice it and show the notes
const version = important ? createHash('sha256').update(content + JSON.stringify(notes)).digest('hex').slice(0, 10) : content;
const info = { version, content, built: new Date().toISOString(), important, notes: important ? notes : [] };
writeFileSync(ROOT + 'version.json', JSON.stringify(info, null, 2) + '\n');

const sw = read('sw.js').toString();
const block = `// @generated by scripts/build-sw.mjs: do not edit\nconst VERSION = '${version}';\nconst PRECACHE = ${JSON.stringify(['./', ...precache], null, 2)};\n// @end-generated`;
writeFileSync(ROOT + 'sw.js', sw.replace(/\/\/ @generated[\s\S]*?\/\/ @end-generated/, block));
console.log(`site version ${version}${important ? ' (important)' : ''}: ${precache.length} files precached, ${files.length} served`);
